/**
 * Small seeded pseudo-random number generator (mulberry32).
 *
 * Same seed => same sequence of numbers, on every reload and every build.
 * We use it instead of Math.random so the "taken" seats never change.
 */
export function seededRandom(seed: number): () => number {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296 // 0 <= n < 1
  }
}

/** Returns a shuffled copy of `items` (Fisher–Yates) using the given random function. */
export function shuffle<T>(items: readonly T[], random: () => number): T[] {
  const result = [...items]
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[result[i], result[j]] = [result[j], result[i]]
  }
  return result
}
